                "    \n",
                "    turn = 1\n",
                "    while turn <= max_turns:\n",
                "        # 1. Log the exact outgoing request payload\n",
                "        if verbose:\n",
                "            PayloadLogger.log_request(turn=turn, contents=contents, tools=TOOLS_LIST, model=model)\n",
                "        \n",
                "        # 2. Call Gemini 3.6 Flash\n",
                "        response = client.models.generate_content(\n",
                "            model=model,\n",
                "            contents=contents,\n",
                "            config=config\n",
                "        )\n",
                "        \n",
                "        # 3. Log the exact incoming response payload\n",
                "        if verbose:\n",
                "            PayloadLogger.log_response(turn=turn, response=response)\n",
