                "    print(f\"🚀 STARTING AGENT TASK: \\\"{user_prompt}\\\"\")\n",
                "    print(\"#\"*80)\n",
                "    \n",
                "    # Initialize conversation history with user message\n",
                "    contents = [\n",
                "        types.Content(\n",
                "            role=\"user\",\n",
                "            parts=[types.Part.from_text(text=user_prompt)]\n",
                "        )\n",
                "    ]\n",
                "    \n",
                "    # Configure tools and disable automatic function calling so we control and log every turn\n",
                "    config = types.GenerateContentConfig(\n",
